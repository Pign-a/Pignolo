'use strict';
// Eval cases for the PAID stage A of `lentes-reales` (card section 7): the real snapshots of D1, D2
// and D5 x the four lenses x 1 run = 12 cases, in the pattern of tests/evals/review-cases.js. It
// only WRITES the cases (case.yaml, prompt.md, fixture.sh, graders/); it never runs anything and
// spends nothing. The case graders only check the dispatch and the `json` block of the report;
// detection is graded afterwards, blind, from the kept traces (card section 8).
//
//   node tests/bench/revision/lentes-eval-cases.js --work <work dir> [--out <eval dir>] [--reviewer-model opus] [--cases D1,D2,D5]
// Default --out: tests/evals/generated/lentes-reales-a (not versioned). The eval dir must be below
// the repo because `claude plugin eval . --eval-dir` resolves it relative to the target.
const fs = require('node:fs');
const path = require('node:path');
const { loadCases, snapshotCode, snapshotById, git, parseArgs, DEFAULT_REPO } = require('./lib');
const { dispatchText } = require('./dispatch');
const { dispatched, singleDispatch, said, graderMd } = require('../../evals/review-cases');

const REPO = DEFAULT_REPO;
const caseName = (code, lens) => `lente-${code}-${lens}`;

// In an eval the session runs in the scaffold folder, so the snapshot sits in the current
// directory: tree/ and brief/ are referenced relative to `.` (the card writes <dir>).
function briefText(sha, base) {
  return dispatchText({ sha, base, dir: '.' }).replace('Read only inside .. There', 'Read only inside the current directory (.). There');
}

function fixtureSh(snapshotDir) {
  const src = path.resolve(snapshotDir).replace(/\\/g, '/');
  return [
    '#!/usr/bin/env bash',
    '# Copies the frozen snapshot (tree/ and brief/) generated by tests/bench/revision/snapshot.js.',
    'set -e',
    `cp -R "${src}/." .`,
    '',
  ].join('\n');
}

function promptMd(lens, brief, caseDir, reviewerModel) {
  const pluginDir = path.join(REPO, 'plugins', 'pignolo');
  const rel = path.relative(caseDir, pluginDir);
  const plugin = (path.isAbsolute(rel) ? pluginDir : rel).split(path.sep).join('/');
  const agent = `review-${lens}`;
  return [
    '---',
    'runs: 1',
    'max_turns: 40',
    'timeout_seconds: 900',
    'model: sonnet',
    `plugins: ["${plugin}"]`,
    `tags: [lentes-reales, stage-a, ${lens}, ${reviewerModel}]`,
    'allowed_tools: [Agent, Read, Grep, Glob]',
    '---',
    '',
    `Dispatch the pignolo:${agent} agent (subagent_type pignolo:${agent}, model ${reviewerModel}) with run_in_background false and exactly the brief between the two lines of dashes. Do not read, run or change anything yourself. When the agent returns, reply with only the word RELAYED.`,
    '',
    '----------',
    brief,
    '----------',
    '',
  ].join('\n');
}

function build({ work, out, reviewerModel = 'opus', caseIds, repo = REPO }) {
  const cases = loadCases();
  const A = cases.lentes.stageA;
  const ids = caseIds || A.cases;
  const names = [];
  for (const id of ids) {
    const c = cases.lentes.cases.find((x) => x.id === id);
    if (!c) throw new Error(`caso desconocido: ${id}`);
    const snap = snapshotById(cases, c.snapshot);
    const code = snapshotCode(snap.id);
    const snapDir = path.join(work, 'snapshots', code);
    if (!fs.existsSync(path.join(snapDir, 'tree'))) throw new Error(`falta la instantanea ${snapDir}: correr snapshot.js primero`);
    const sha = git(repo, ['rev-parse', snap.commit]).trim();
    const base = git(repo, ['rev-parse', snap.parent]).trim();
    for (const lens of A.lenses) {
      const name = caseName(code, lens);
      const dir = path.join(out, name);
      fs.rmSync(dir, { recursive: true, force: true });
      fs.mkdirSync(path.join(dir, 'graders'), { recursive: true });
      fs.writeFileSync(path.join(dir, 'case.yaml'), `schema_version: "1.1"\nname: ${name}\ncontext:\n  scaffold_script: fixture.sh\n`);
      fs.writeFileSync(path.join(dir, 'fixture.sh'), fixtureSh(snapDir));
      fs.writeFileSync(path.join(dir, 'prompt.md'), promptMd(lens, briefText(sha, base), dir, reviewerModel));
      const agent = `review-${lens}`;
      const graders = [...dispatched(agent, reviewerModel), singleDispatch, said(agent, 'subagent-returned', '```json')];
      for (const g of graders) fs.writeFileSync(path.join(dir, 'graders', `${g.name}.md`), graderMd(g));
      names.push({ name, case: id, lens, code });
    }
  }
  return names;
}

function commands(outRel, probeName) {
  const common = '--ablation none --scaffold --trust-plugin --keep-temp --no-publish';
  const A = loadCases().lentes.stageA;
  return {
    probe: `claude plugin eval . --eval-dir ${outRel} --case ${probeName} --runs ${A.runs} ${common} --max-cost-usd ${A.probeMaxCostUsd} --json ${outRel}/probe.json`,
    stage: `claude plugin eval . --eval-dir ${outRel} --runs ${A.runs} ${common} --max-cost-usd ${A.stageMaxCostUsd} -j 2 --json ${outRel}/stage-a.json`,
    // Fallback if the probe costs more than 0.37 USD (card): only D1 and D2, one command per case
    // (the runner takes one --case glob), each with half of the stage ceiling.
    stageCase: (code, n) => `claude plugin eval . --eval-dir ${outRel} --case "lente-${code}-*" --runs ${A.runs} ${common} --max-cost-usd ${A.stageMaxCostUsd / 2} -j 2 --json ${outRel}/stage-a-${n}.json`,
  };
}

if (require.main === module) {
  const a = parseArgs(process.argv.slice(2));
  if (!a.work) {
    process.stderr.write('uso: node lentes-eval-cases.js --work <work dir> [--out <eval dir>] [--reviewer-model opus] [--cases D1,D2,D5]\n');
    process.exit(2);
  }
  try {
    const out = path.resolve(a.out || path.join(REPO, 'tests', 'evals', 'generated', 'lentes-reales-a'));
    const cases = build({ work: path.resolve(a.work), out, reviewerModel: a['reviewer-model'] || 'opus', caseIds: a.cases ? String(a.cases).split(',') : undefined });
    const outRel = path.relative(REPO, out).split(path.sep).join('/');
    const probe = cases.find((c) => c.case === loadCases().lentes.probe.case && c.lens === loadCases().lentes.probe.lens);
    const cmd = commands(outRel, probe.name);
    const d1 = cases.find((c) => c.case === 'D1');
    const d2 = cases.find((c) => c.case === 'D2');
    process.stdout.write(`${JSON.stringify({ out, cases: cases.map((c) => c.name) })}\n\nDesde la raiz del repo (${REPO}):\n\n1. Sonda paga de 1 corrida (D2, reliability):\n${cmd.probe}\n\n2. Etapa A (12 corridas), solo si la sonda costo <= 0,37 USD:\n${cmd.stage}\n\n   Si la sonda costo mas de 0,37 USD (8 corridas, D1 y D2), dos comandos en lugar del anterior:\n   ${cmd.stageCase(d1.code, 'D1')}\n   ${cmd.stageCase(d2.code, 'D2')}\n\nTope total 0,6 + 4,4 = 5 USD. Despues: leak-check.js sobre cada out/trace.jsonl de los temporales (--keep-temp).\n`);
  } catch (e) {
    process.stderr.write(`lentes-eval-cases: ${e.message}\n`);
    process.exit(1);
  }
}

module.exports = { build, briefText, fixtureSh, promptMd, commands, caseName };
